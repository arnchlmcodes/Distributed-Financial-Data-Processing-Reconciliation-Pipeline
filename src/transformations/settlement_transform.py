"""
settlement_transform.py — Match transactions with settlements; detect reconciliation issues.

Rules:
- Match on transaction_id (left join: transactions LEFT JOIN settlements)
- Compute amount_difference = |txn.amount - stl.settled_amount| (both in DecimalType(18,2))
- Reconciliation tolerance from config (default 0.01)
- Issue types detected here: MISSING_SETTLEMENT, AMOUNT_MISMATCH, DUPLICATE_SETTLEMENT, DELAYED_SETTLEMENT
- One row per issue in reconciliation_issues
- Write matched parquet partitioned by batch_id
"""
from __future__ import annotations

import logging
from decimal import Decimal

from pyspark.sql import DataFrame, SparkSession
from pyspark.sql import functions as F
from pyspark.sql.types import DecimalType, StringType
from pyspark.sql.window import Window

from src.config import settings

logger = logging.getLogger(__name__)

# Issue type constants
MISSING_SETTLEMENT = "MISSING_SETTLEMENT"
AMOUNT_MISMATCH = "AMOUNT_MISMATCH"
DUPLICATE_SETTLEMENT = "DUPLICATE_SETTLEMENT"
DELAYED_SETTLEMENT = "DELAYED_SETTLEMENT"
ORPHAN_SETTLEMENT = "ORPHAN_SETTLEMENT"

# Delay threshold in hours
SETTLEMENT_DELAY_HOURS = 48


def match_settlements(
    txn_df: DataFrame,
    stl_df: DataFrame,
) -> DataFrame:
    """
    Left join transactions with settlements on transaction_id.

    Args:
        txn_df: Clean transactions (transaction_id, amount, transaction_timestamp, ...)
        stl_df: Settlements (settlement_id, transaction_id, settled_amount, settlement_timestamp, ...)

    Returns:
        Joined DataFrame with columns from both, nulls where no settlement.
    """
    # Rename settlement columns to avoid ambiguity
    cols = [
        F.col("settlement_id"),
        F.col("transaction_id").alias("stl_transaction_id"),
        F.col("settled_amount"),
        F.col("settlement_currency"),
        F.col("settlement_timestamp"),
        F.col("status").alias("settlement_status"),
    ]
    if "batch_id" in stl_df.columns:
        cols.append(F.col("batch_id").alias("stl_batch_id"))

    stl_renamed = stl_df.select(*cols)

    matched = txn_df.join(
        stl_renamed,
        on=(txn_df["transaction_id"] == stl_renamed["stl_transaction_id"]),
        how="left",
    ).drop("stl_transaction_id", "stl_batch_id")

    logger.info("Settlement join complete — total rows: %d", matched.count())
    return matched


def detect_issues(
    matched_df: DataFrame,
    batch_id: str,
    tolerance: Decimal | None = None,
) -> DataFrame:
    """
    Detect reconciliation issues in the matched DataFrame.

    Returns a DataFrame in reconciliation_issues format:
    - issue_id (omitted, generated by DB)
    - batch_id, transaction_id, settlement_id
    - issue_type, amount_difference, expected_amount, actual_amount
    - currency, details (JSON str), detected_at
    """
    tol = float(tolerance or settings.reconciliation_tolerance)

    # Compute amount_difference (Decimal, 2dp)
    df = matched_df.withColumn(
        "amount_difference",
        F.when(
            F.col("settled_amount").isNotNull(),
            F.abs(F.col("amount") - F.col("settled_amount")).cast(DecimalType(18, 2)),
        ).otherwise(F.lit(None).cast(DecimalType(18, 2))),
    )

    # Build issue rows — one union per issue type

    # 1. MISSING_SETTLEMENT: no settlement record
    missing = df.filter(F.col("settlement_id").isNull()).select(
        F.lit(batch_id).alias("batch_id"),
        F.col("transaction_id"),
        F.lit(None).cast(StringType()).alias("settlement_id"),
        F.lit(MISSING_SETTLEMENT).alias("issue_type"),
        F.col("amount_difference"),
        F.col("amount").cast(DecimalType(18, 2)).alias("expected_amount"),
        F.lit(None).cast(DecimalType(18, 2)).alias("actual_amount"),
        F.col("currency"),
        F.to_json(F.struct(F.col("type").alias("txn_type"), F.col("step"))).alias("details"),
        F.current_timestamp().alias("detected_at"),
    )

    # 2. AMOUNT_MISMATCH: |difference| > tolerance
    mismatch = df.filter(
        F.col("settlement_id").isNotNull() &
        (F.col("amount_difference") > F.lit(tol).cast(DecimalType(18, 2)))
    ).select(
        F.lit(batch_id).alias("batch_id"),
        F.col("transaction_id"),
        F.col("settlement_id"),
        F.lit(AMOUNT_MISMATCH).alias("issue_type"),
        F.col("amount_difference"),
        F.col("amount").cast(DecimalType(18, 2)).alias("expected_amount"),
        F.col("settled_amount").cast(DecimalType(18, 2)).alias("actual_amount"),
        F.col("currency"),
        F.to_json(F.struct(F.col("amount_difference"), F.col("settlement_status"))).alias("details"),
        F.current_timestamp().alias("detected_at"),
    )

    # 3. DELAYED_SETTLEMENT: settlement_timestamp - transaction_timestamp > 48h
    delay_seconds = SETTLEMENT_DELAY_HOURS * 3600
    delayed = df.filter(
        F.col("settlement_id").isNotNull() &
        (
            (F.col("settlement_timestamp").cast("long") - F.col("transaction_timestamp").cast("long"))
            > delay_seconds
        )
    ).select(
        F.lit(batch_id).alias("batch_id"),
        F.col("transaction_id"),
        F.col("settlement_id"),
        F.lit(DELAYED_SETTLEMENT).alias("issue_type"),
        F.lit(None).cast(DecimalType(18, 2)).alias("amount_difference"),
        F.col("amount").cast(DecimalType(18, 2)).alias("expected_amount"),
        F.col("settled_amount").cast(DecimalType(18, 2)).alias("actual_amount"),
        F.col("currency"),
        F.to_json(
            F.struct(
                F.col("settlement_timestamp").alias("settlement_ts"),
                F.col("transaction_timestamp").alias("txn_ts"),
            )
        ).alias("details"),
        F.current_timestamp().alias("detected_at"),
    )

    # Union all issues
    issues = missing.unionByName(mismatch).unionByName(delayed)

    issue_count = issues.count()
    logger.info(
        "Issues detected — batch=%s: MISSING_SETTLEMENT=%d, AMOUNT_MISMATCH=%d, DELAYED=%d, total=%d",
        batch_id,
        missing.count(),
        mismatch.count(),
        delayed.count(),
        issue_count,
    )

    return issues


def detect_duplicate_settlements(
    stl_df: DataFrame,
    batch_id: str,
) -> DataFrame:
    """
    Detect duplicate settlements: same transaction_id with multiple settlement records.
    Returns issue rows for each duplicate (beyond the first).
    """
    w_stl = Window.partitionBy("transaction_id").orderBy("settlement_timestamp")
    ranked = stl_df.withColumn("_stl_rank", F.row_number().over(w_stl))

    dups = ranked.filter(F.col("_stl_rank") > 1)

    issues = dups.select(
        F.lit(batch_id).alias("batch_id"),
        F.col("transaction_id"),
        F.col("settlement_id"),
        F.lit(DUPLICATE_SETTLEMENT).alias("issue_type"),
        F.lit(None).cast(DecimalType(18, 2)).alias("amount_difference"),
        F.lit(None).cast(DecimalType(18, 2)).alias("expected_amount"),
        F.col("settled_amount").cast(DecimalType(18, 2)).alias("actual_amount"),
        F.col("settlement_currency").alias("currency"),
        F.to_json(F.struct(F.col("settlement_id"), F.col("settlement_timestamp"))).alias("details"),
        F.current_timestamp().alias("detected_at"),
    )

    dup_count = issues.count()
    logger.info("Duplicate settlements detected: %d", dup_count)
    return issues


def detect_orphan_settlements(
    stl_df: DataFrame,
    txn_df: DataFrame,
    batch_id: str,
) -> DataFrame:
    """
    Detect orphan settlements: settlements with no matching transaction.
    """
    txn_ids = txn_df.select("transaction_id").distinct()

    orphans = stl_df.join(txn_ids, on="transaction_id", how="left_anti")

    issues = orphans.select(
        F.lit(batch_id).alias("batch_id"),
        F.col("transaction_id"),
        F.col("settlement_id"),
        F.lit(ORPHAN_SETTLEMENT).alias("issue_type"),
        F.lit(None).cast(DecimalType(18, 2)).alias("amount_difference"),
        F.lit(None).cast(DecimalType(18, 2)).alias("expected_amount"),
        F.col("settled_amount").cast(DecimalType(18, 2)).alias("actual_amount"),
        F.col("settlement_currency").alias("currency"),
        F.to_json(F.struct(F.col("settlement_id"), F.col("settlement_timestamp"))).alias("details"),
        F.current_timestamp().alias("detected_at"),
    )

    orphan_count = issues.count()
    logger.info("Orphan settlements detected: %d", orphan_count)
    return issues


def run_settlement_transform(
    spark: SparkSession,
    txn_df: DataFrame,
    stl_df: DataFrame,
    batch_id: str,
    output_dir: str,
) -> tuple[DataFrame, int]:
    """
    Full settlement matching and issue detection pipeline.

    Returns:
        (all_issues_df, total_issues_count)
    """
    logger.info("Starting settlement transform for batch=%s", batch_id)

    # Match
    matched = match_settlements(txn_df, stl_df)

    # Detect issues
    issues_main = detect_issues(matched, batch_id)
    dup_issues = detect_duplicate_settlements(stl_df, batch_id)
    orphan_issues = detect_orphan_settlements(stl_df, txn_df, batch_id)

    all_issues = issues_main.unionByName(dup_issues).unionByName(orphan_issues)
    total_issues = all_issues.count()

    # Write issues parquet
    issues_path = f"{output_dir}/reconciliation_issues/batch_id={batch_id}"
    (
        all_issues.write.mode("overwrite")
        .option("compression", "snappy")
        .parquet(issues_path)
    )
    logger.info("Reconciliation issues written to %s (%d rows)", issues_path, total_issues)

    # Write matched parquet (for loading to warehouse)
    matched_path = f"{output_dir}/matched/batch_id={batch_id}"
    (
        matched.write.mode("overwrite")
        .option("compression", "snappy")
        .parquet(matched_path)
    )

    return all_issues, total_issues

